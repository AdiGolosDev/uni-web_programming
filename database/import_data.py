def read_csv(filename):
    path = CSV_DIR / filename
    if not path.exists():
        sys.exit(f"Missing file: {path}\nDownload it from PokeAPI's data/v2/csv/ folder.")
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))

def sql_str(value):
    """Quote a string for SQL (escapes backslashes and apostrophes, e.g. Farfetch'd)."""
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"

def write_inserts(out, table, columns, rows, chunk=100):
    """Write INSERT statements in chunks so no single statement gets huge."""
    cols = ", ".join(columns)
    for i in range(0, len(rows), chunk):
        part = rows[i:i + chunk]
        out.write(f"INSERT INTO {table} ({cols}) VALUES\n")
        out.write(",\n".join("(" + ", ".join(r) + ")" for r in part))
        out.write(";\n\n")

def main():
    if not SQL_FILE.exists():
        sys.exit(f"Could not find {SQL_FILE}\n"
                 "This script must be in the same folder as pokeplanner.sql.")

    types = []
    for row in read_csv("types.csv"):
        tid = int(row["id"])
        if tid <= MAX_TYPE_ID:
            types.append((tid, row["identifier"].capitalize()))
    types.sort()

    effectiveness = []
    for row in read_csv("type_efficacy.csv"):
        attacker = int(row["damage_type_id"])
        defender = int(row["target_type_id"])
        if attacker <= MAX_TYPE_ID and defender <= MAX_TYPE_ID:
            multiplier = int(row["damage_factor"]) / 100   # 0, 50, 100, 200 -> 0, 0.5, 1, 2
            effectiveness.append((attacker, defender, multiplier))
    effectiveness.sort()

    english_names = {}
    for row in read_csv("pokemon_species_names.csv"):
        if row["local_language_id"] == ENGLISH_ID:
            english_names[int(row["pokemon_species_id"])] = row["name"]

    generations = {}
    for row in read_csv("pokemon_species.csv"):
        generations[int(row["id"])] = int(row["generation_id"])

    pokemon_types = {}
    for row in read_csv("pokemon_types.csv"):
        pid = int(row["pokemon_id"])
        if pid <= MAX_DEX:
            pokemon_types.setdefault(pid, {})[int(row["slot"])] = int(row["type_id"])

    pokemon_stats = {}
    for row in read_csv("pokemon_stats.csv"):
        pid = int(row["pokemon_id"])
        column = STAT_COLUMNS.get(row["stat_id"])    # ignores accuracy/evasion if present
        if pid <= MAX_DEX and column:
            pokemon_stats.setdefault(pid, {})[column] = int(row["base_stat"])

    pokemon = []
    for row in read_csv("pokemon.csv"):
        pid = int(row["id"])
        if pid > MAX_DEX:
            continue                                  # alternate forms (ids above 10000)
        species_id = int(row["species_id"])
        name = english_names.get(species_id) or row["identifier"].replace("-", " ").title()
        slots = pokemon_types[pid]
        stats = pokemon_stats[pid]
        pokemon.append({
            "id": pid,
            "name": name,
            "generation": generations[species_id],
            "type1": slots[1],
            "type2": slots.get(2),
            "stats": stats,
        })
    pokemon.sort(key=lambda p: p["id"])

    # ---- build the sample data section -----------------------------
    data = io.StringIO()

    write_inserts(data, "types", ["id", "name"],
                  [[str(tid), sql_str(name)] for tid, name in types])

    write_inserts(data, "type_effectiveness",
                  ["attacker_type_id", "defender_type_id", "multiplier"],
                  [[str(a), str(d), f"{m:.1f}"] for a, d, m in effectiveness])

    write_inserts(data, "games", ["name", "generation", "release_year"],
                  [[sql_str(n), str(g), str(y)] for n, g, y in GAMES])

    write_inserts(
        data, "pokemon",
        ["id", "dex_number", "name", "generation", "type1_id", "type2_id",
         "sprite_url", "hp", "attack", "defense", "sp_atk", "sp_def", "speed"],
        [[
            str(p["id"]), str(p["id"]), sql_str(p["name"]), str(p["generation"]),
            str(p["type1"]), str(p["type2"]) if p["type2"] else "NULL",
            sql_str(SPRITE_URL.format(p["id"])),
            str(p["stats"]["hp"]), str(p["stats"]["attack"]), str(p["stats"]["defense"]),
            str(p["stats"]["sp_atk"]), str(p["stats"]["sp_def"]), str(p["stats"]["speed"]),
        ] for p in pokemon],
    )

    # rewrite pokeplanner.sql
    with open(SQL_FILE, encoding="utf-8") as f:
        content = f.read()

    schema_part = content.split(SEED_MARKER)[0].rstrip()

    with open(SQL_FILE, "w", encoding="utf-8") as f:
        f.write(schema_part)
        f.write("\n\n")
        f.write("-- ---------------------------------------------------------------------\n")
        f.write(SEED_MARKER + "\n")
        f.write("-- Source: PokeAPI CSV files (database/pokeapi_csv/). Re-run generate_seed.py to rebuild.\n")
        f.write("-- ---------------------------------------------------------------------\n\n")
        f.write(data.getvalue())

    # ---- sanity checks
    print(f"Updated {SQL_FILE}")
    print(f"  types:              {len(types)}   (expected 18)")
    print(f"  type_effectiveness: {len(effectiveness)}  (expected 324)")
    print(f"  games:              {len(GAMES)}")
    print(f"  pokemon:            {len(pokemon)} (expected {MAX_DEX})")
    if len(types) != 18 or len(effectiveness) != 324 or len(pokemon) != MAX_DEX:
        print("WARNING: a count does not match what was expected - check the CSV files.")


if __name__ == "__main__":
    main()
    